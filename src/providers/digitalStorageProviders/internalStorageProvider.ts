import fs from "fs";
import path from "path";
import crypto from "crypto";
import { STORAGE_ROOT, detectAndValidateFile } from "../../helpers/fileStorage";
import { signDigitalStoreUrl } from "../../helpers/digitalFileSigning";
import { IDigitalFile } from "../../models/digitalFile";
import { DigitalStorageProviderAdapter, DigitalStorageUploadOutcome } from "./types";

// The local-disk DigitalStorageProviderAdapter — the default (see
// providers/digitalStorageProviders/index.ts) until real AWS credentials
// exist. A digital product/purchase file's `key` here is a relative path
// under its own directory, kept separate from PUBLIC_DIR/PRIVATE_DIR
// (fileStorage.ts) since this is a distinct concern with its own
// buyer-copy semantics — never mixed with avatars/logos/portfolio media.
export const DIGITAL_STORE_DIR = path.join(STORAGE_ROOT, "digital-store");
fs.mkdirSync(DIGITAL_STORE_DIR, { recursive: true });

const safeName = (originalName: string): string =>
  originalName.replace(/\s+/g, "").replace(/[^a-zA-Z0-9.\-_]/g, "") || "file";

// A `key` is always generated by this module (never client-supplied), but
// resolving it defensively anyway — joined relative to DIGITAL_STORE_DIR
// and then required to still start with it, the same "never trust a path
// segment" instinct PRIVATE_DIR's `root`-option protection exists for.
const keyToPath = (key: string): string => {
  const resolved = path.join(DIGITAL_STORE_DIR, key);

  if (!resolved.startsWith(DIGITAL_STORE_DIR + path.sep)) {
    throw new Error("Invalid digital-store key");
  }

  return resolved;
};

export const internalStorageProvider: DigitalStorageProviderAdapter = {
  async uploadDigitalFiles(
    files: Express.Multer.File[],
    keyPrefix: string,
    allowedMimeTypes: string[],
  ): Promise<DigitalStorageUploadOutcome> {
    const results: IDigitalFile[] = [];
    const errorLogs: string[] = [];

    for (const file of files) {
      try {
        const detected = detectAndValidateFile(file.buffer, file.originalname, allowedMimeTypes);

        if (!detected.ok) {
          errorLogs.push(detected.error);
          continue;
        }

        const key = `${keyPrefix}/${crypto.randomUUID()}-${safeName(file.originalname)}`;
        const fullPath = keyToPath(key);
        await fs.promises.mkdir(path.dirname(fullPath), { recursive: true });
        await fs.promises.writeFile(fullPath, file.buffer);

        results.push({ fileName: file.originalname, key, mime: detected.mime, size: file.buffer.length });
      } catch (err) {
        errorLogs.push(`Error processing file ${file.originalname}: ${(err as Error).message}`);
      }
    }

    return { results, errorLogs };
  },

  async copyDigitalFile(sourceKey: string, destKey: string): Promise<void> {
    const destPath = keyToPath(destKey);
    await fs.promises.mkdir(path.dirname(destPath), { recursive: true });
    await fs.promises.copyFile(keyToPath(sourceKey), destPath);
  },

  async deleteDigitalFile(key: string): Promise<void> {
    try {
      await fs.promises.unlink(keyToPath(key));
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code !== "ENOENT") throw err;
    }
  },

  async getDigitalFileDownloadUrl(key: string, fileName: string, mime: string): Promise<string> {
    return signDigitalStoreUrl(key, fileName, mime);
  },
};
